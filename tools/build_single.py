#!/usr/bin/env python3
"""
Build helper of the TwinPulse Hedge EA (the only Python of this project).

It inlines every project header of MQL5/Include/TwinPulse into
MQL5/Experts/TwinPulse/TwinPulse.mq5 and writes the result to
dist/TwinPulse_single.mq5 so that the EA can be compiled as one file
inside MQL5/Experts.

The standard library headers (<Trade/...>) are kept as they are.

Usage:  python3 tools/build_single.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "MQL5", "Experts", "TwinPulse", "TwinPulse.mq5")
INC = os.path.join(ROOT, "MQL5", "Include")
OUT = os.path.join(ROOT, "dist", "TwinPulse_single.mq5")

INCLUDE_RE = re.compile(r'^\s*#include\s+([<"])([^>"]+)[>"]')


def resolve(path, base_dir=None):
    """Return the project file of an include or None for the standard library."""
    rel = path.replace("\\", "/")
    candidates = []
    if base_dir:
        candidates.append(os.path.join(base_dir, rel.replace("/", os.sep)))
    candidates.append(os.path.join(INC, rel))
    candidates.append(os.path.join(INC, rel.replace("/", os.sep)))
    for cand in candidates:
        if os.path.isfile(cand):
            return cand
    return None


def inline(text, seen, out, base_dir=None):
    for line in text.splitlines():
        match = INCLUDE_RE.match(line)
        if not match:
            out.append(line)
            continue

        quote, path = match.group(1), match.group(2)
        target = resolve(path, base_dir)
        if target is None:
            out.append(line)
            continue

        if target in seen:
            out.append("// (already inlined) project header: %s" % path)
            continue

        seen.add(target)
        rel = os.path.relpath(target, ROOT)
        out.append("//+--- begin %s " % rel + "-" * max(0, 60 - len(rel)))
        with open(target, "r", encoding="utf-8") as handle:
            body = handle.read()
        inline(body, seen, out, os.path.dirname(target))
        out.append("//+--- end %s " % rel + "-" * max(0, 60 - len(rel)))


def main():
    if not os.path.isfile(SRC):
        print("source not found: %s" % SRC)
        return 1

    with open(SRC, "r", encoding="utf-8") as handle:
        source = handle.read()

    body = []
    inline(source, set(), body, os.path.dirname(SRC))

    header = [
        "//+------------------------------------------------------------------+",
        "//|                                                 TwinPulse_single.mq5",
        "//|  TwinPulse Hedge EA - single file build, generated by tools/build_single.py",
        "//|  Do not edit this file, edit the modular sources and rebuild.        ",
        "//+------------------------------------------------------------------+",
        "#property copyright \"TwinPulse Hedge EA\"",
        "#property version   \"1.00\"",
        "#property description \"TwinPulse Hedge EA - single file build (all project headers inlined).\"",
        "",
    ]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(header + body) + "\n")

    # --- sanity checks -------------------------------------------------
    with open(OUT, "r", encoding="utf-8") as handle:
        written = handle.read()

    problems = []
    active = [l for l in written.splitlines() if not l.lstrip().startswith("//")]
    active_text = "\n".join(active)

    if re.search(r'^\s*#include\s+[<"](?:TwinPulse/|TwinPulse\\)', active_text, re.MULTILINE):
        problems.append("a project include was not inlined")
    if re.search(r'^\s*#pragma\b', active_text, re.MULTILINE):
        problems.append("an unsupported or unexpected #pragma survived inlining")
    for line in active:
        match = INCLUDE_RE.match(line)
        if match and resolve(match.group(2)) is not None:
            problems.append("unresolved project include: %s" % match.group(2))
            break
    if re.search(r'#include\s+"', active_text):
        problems.append("a relative include survived the inlining")

    print("single file written: %s" % OUT)
    print("lines: %d, size: %d bytes" % (len(written.splitlines()), len(written)))
    if problems:
        for problem in problems:
            print("PROBLEM: %s" % problem)
        return 1
    print("check: no project includes or unsupported pragmas left, OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
