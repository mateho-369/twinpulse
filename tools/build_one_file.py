#!/usr/bin/env python3
"""
Build the ONE-FILE scalper: every tested variant inside a single .mq5.

The owner asked for one file to compile and backtest by hand instead of
34 preset files plus a PowerShell batch. This tool takes the real source
(MQL5/Experts/TwinPulse/TwinPulseScalp.mq5) and the real presets
(tester/scalp3, tester/scalp2, tester/scalp) and emits

    MQL5/Experts/TwinPulse/TwinPulseONE.mq5

with a `InpPreset` enum. TP_CUSTOM (the default) behaves exactly like the
source EA with the inputs as typed - so an old .set still works. Any other
value overrides the inputs that the presets actually change, in OnInit,
before a single indicator handle is created.

Nothing here is hand-written into the output: edit the source or the .set
files, rerun this tool. `--check` only verifies that the committed file is
up to date.

Usage:  python3 tools/build_one_file.py [--check]
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "MQL5", "Experts", "TwinPulse", "TwinPulseScalp.mq5")
OUT = os.path.join(ROOT, "MQL5", "Experts", "TwinPulse", "TwinPulseONE.mq5")
PRESET_DIRS = ("tester/scalp3",)   # the only source of the survey

INPUT_RE = re.compile(r"^input\s+(long|string|bool|double|int)\s+(\w+)\s*=\s*([^;]+);")
NUMERIC = {"double": "double", "int": "int", "long": "long", "bool": "bool"}


def read(path):
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def load_set(path):
    values = {}
    for line in read(path).splitlines():
        line = line.strip()
        if not line or line.startswith(";") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def sort_key(variant):
    """S1..S11 then X1..X6, each `_N` twin right after its base."""
    match = re.match(r"^([A-Za-z]+)(\d+)(.*)$", variant)
    if not match:
        return (variant, 0, "")
    return (match.group(1), int(match.group(2)), match.group(3))


def enum_name(variant):
    return "TP_" + re.sub(r"[^A-Za-z0-9_]", "_", variant)


def presets():
    """Every distinct variant of the survey, in a stable natural order."""
    found = {}
    for folder in PRESET_DIRS:
        path = os.path.join(ROOT, folder)
        if not os.path.isdir(path):
            continue
        for name in os.listdir(path):
            if name.endswith(".set"):
                found[name[:-4]] = load_set(os.path.join(path, name))
    order = sorted(found, key=sort_key)
    return order, found


def numeric(value):
    """The MQL5 literal for a .set string, keeping ints integral."""
    text = value.strip()
    if re.fullmatch(r"[+-]?\d+", text):
        return text
    return "%.2f" % float(text)


def main():
    check_only = "--check" in sys.argv

    source = read(SRC)
    lines = source.splitlines()

    # --- split the input block from the program body --------------------
    first = next(i for i, l in enumerate(lines) if l.startswith("input "))
    last = max(i for i, l in enumerate(lines) if l.startswith("input "))
    declared, types, defaults = [], {}, {}
    for line in lines[first:last + 1]:
        match = INPUT_RE.match(line)
        if not match:
            continue
        kind, name, default = match.group(1), match.group(2), match.group(3).strip()
        declared.append(name)
        types[name] = kind
        defaults[name] = default

    order, table = presets()
    if not order:
        print("no presets found")
        return 1

    # --- which inputs does a preset actually touch? ---------------------
    varied = []
    for name in declared:
        if types[name] == "string":
            continue
        seen = {table[v].get(name) for v in order}
        if len(seen) > 1 or (seen and None in seen):
            varied.append(name)
    for name in varied:
        missing = [v for v in order if name not in table[v]]
        if missing:
            print("preset %s does not set %s" % (missing[0], name))
            return 1

    # --- rename the body uses so a preset can change them ---------------
    body = "\n".join(lines[last + 1:])
    for name in sorted(varied, key=len, reverse=True):
        body = re.sub(r"\b%s\b" % name, "CFG_" + name, body)
    for name in varied:
        if re.search(r"\b%s\b" % ("CFG_" + name), source):
            print("CFG_%s already exists in the source" % name)
            return 1

    # --- the generated preset block -------------------------------------
    gen = ["", "//+------------------------------------------------------------------+",
           "//|  GENERATED by tools/build_one_file.py - do not edit by hand.      |",
           "//|  One file, every variant: pick InpPreset, or TP_CUSTOM to use the |",
           "//|  inputs below exactly as typed (the old .set files still load).   |",
           "//+------------------------------------------------------------------+",
           "enum ENUM_TP_PRESET", "  {",
           "   TP_CUSTOM = 0,                          // custom - use the inputs below"]
    for i, variant in enumerate(order, 1):
        label = "%s = %d," % (enum_name(variant), i)
        gen.append("   %s%s// %s" % (label, " " * max(2, 42 - len(label)), variant))
    gen.append("  };")
    gen.append("")
    gen.append("input ENUM_TP_PRESET InpPreset = TP_CUSTOM;   // Preset: a tested variant, or custom")
    gen.append("")
    for name in varied:
        gen.append("%-8s CFG_%s;" % (types[name], name))
    gen.append("")

    gen.append("string TP_PresetLabel()")
    gen.append("  {")
    gen.append("   switch(InpPreset)")
    gen.append("     {")
    for i, variant in enumerate(order, 1):
        gen.append('      case %s: return "%s";' % (enum_name(variant), variant))
    gen.append("     }")
    gen.append('   return "custom";')
    gen.append("  }")
    gen.append("")

    gen.append("//--- every preset value is absolute: no dependence on what the")
    gen.append("//--- inputs were before, so a saved .set cannot leak into a preset")
    gen.append("void TP_ApplyPreset()")
    gen.append("  {")
    for name in varied:
        gen.append("   CFG_%s = %s;" % (name, name))
    gen.append("   if(InpPreset == TP_CUSTOM) return;")
    gen.append("")
    gen.append("   switch(InpPreset)")
    gen.append("     {")
    for i, variant in enumerate(order, 1):
        gen.append("      case %s:" % enum_name(variant))
        for name in varied:
            gen.append("         CFG_%s = %s;" % (name, numeric(table[variant][name])))
        gen.append("         break;")
    gen.append("     }")
    gen.append("")
    gen.append('   PrintFormat("TwinPulseONE preset %s applied (%d of %d inputs overridden)",')
    gen.append('               TP_PresetLabel(), %d, %d);' % (len(varied), len(declared)))
    gen.append("  }")
    gen.append("//+------------------------------------------------------------------+")
    gen.append("")

    out_lines = lines[:last + 1] + gen + body.splitlines()

    # --- OnInit: apply the preset before anything reads a parameter -----
    text = "\n".join(out_lines)
    anchor = "int OnInit(void)\n  {\n"
    if anchor not in text:
        print("OnInit anchor not found")
        return 1
    text = text.replace(anchor,
                        anchor +
                        "   //--- the preset must land before the first handle or parameter read\n"
                        "   TP_ApplyPreset();\n\n", 1)

    header = "\n".join([
        "//+------------------------------------------------------------------+",
        "//|  TwinPulseONE.mq5 - ALL %d tested variants in ONE file" % len(order),
        "//|  XAUUSDm M5 scalper, fixed 0.01 lot, broker SL on every leg,",
        "//|  AllowLive=false, no grid, no averaging down.",
        "//|  Pick the variant with the InpPreset input. TP_CUSTOM = the inputs",
        "//|  exactly as typed, which is how every old .set file behaves.",
        "//|  GENERATED by tools/build_one_file.py - edit the source, not this.",
        "//+------------------------------------------------------------------+",
        "",
    ])

    text = header + text + "\n"
    text = text.replace('#property version   "1.00"', '#property version   "1.13"', 1)
    # one CSV per preset, so 34 manual tester runs do not overwrite each
    # other. A batch run (TP_CUSTOM, i.e. a .set file) keeps the old name.
    text = text.replace(
        '      g_csv = FileOpen("TwinPulse_legs.csv",',
        '      g_csv = FileOpen(g_csvName,', 1)
    text = text.replace(
        '   if(InpWriteCsv)\n     {\n      g_csv = FileOpen(g_csvName,',
        '   if(InpPreset == TP_CUSTOM)\n      g_csvName = "TwinPulse_legs.csv";\n'
        '   else\n      g_csvName = "TwinPulse_legs_" + TP_PresetLabel() + ".csv";\n\n'
        '   if(InpWriteCsv)\n     {\n      g_csv = FileOpen(g_csvName,', 1)
    text = text.replace('int      g_csv = INVALID_HANDLE;',
                        'int      g_csv = INVALID_HANDLE;\nstring   g_csvName = "TwinPulse_legs.csv";', 1)
    text = text.replace('TPS 1.13 start', 'TPS 1.13 ONE start', 1)
    # the preset name belongs in the first line of every log
    text = text.replace('ONE start %s mode=%d entry=%d',
                        'ONE start %s preset=%s mode=%d entry=%d', 1)
    text = text.replace('_Symbol, CFG_InpMode, CFG_InpEntryMode,',
                        '_Symbol, TP_PresetLabel(), CFG_InpMode, CFG_InpEntryMode,', 1)

    # --- static checks we can do without MetaEditor ---------------------
    problems = []
    if text.count("{") != text.count("}"):
        problems.append("brace mismatch %d/%d" % (text.count("{"), text.count("}")))
    for name in varied:
        left = re.findall(r"(?<!CFG_)\b%s\b" % name, body)
        if left:
            problems.append("%s still used in the body" % name)
    if re.search(r"^\s*#include\s+[<\"]+(?!Trade[\\/])", text, re.MULTILINE):
        problems.append("a non-standard include survived")
    if text.count("int OnInit(void)") != 1 or text.count("TP_ApplyPreset();") != 1:
        problems.append("TP_ApplyPreset is not wired once into OnInit")
    if "InpPreset" not in text.split("int OnInit")[0] or text.count("input ENUM_TP_PRESET") != 1:
        problems.append("the preset input is missing or duplicated")

    if check_only:
        current = read(OUT) if os.path.isfile(OUT) else ""
        if current != text:
            print("STALE: %s does not match the source" % OUT)
            return 1
        print("up to date: %s" % OUT)
        return 0

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)

    print("written: %s" % OUT)
    print("lines: %d, presets: %d, overridden inputs: %d"
          % (len(text.splitlines()), len(order), len(varied)))
    print("overridden: %s" % ", ".join(varied))
    if problems:
        for problem in problems:
            print("PROBLEM: %s" % problem)
        return 1
    print("static checks: braces, includes, preset wiring - OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
